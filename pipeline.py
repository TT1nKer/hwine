def gen_vivado_rtl(N: int, op: AtomOp, pipeline: bool = False) -> str:
    """Generate clean RTL with DSP48 inference hints and pipeline registers."""
    eg = EGraph()
    if op in (AtomOp.ADD, AtomOp.REDUCE_MIN, AtomOp.REDUCE_MAX):
        vs = [eg.add(ENode(AtomOp.VAR, (f"v{i}",))) for i in range(N)]
        c = vs[0]
        for i in range(1, N): c = eg.add(ENode(op, (c, vs[i])))
    else:  # MAC
        z = eg.add(ENode(AtomOp.ZERO, ()))
        ws = [eg.add(ENode(AtomOp.VAR, (f"w{i}",))) for i in range(N)]
        a_ = [eg.add(ENode(AtomOp.VAR, (f"a{i}",))) for i in range(N)]
        ai = eg.add(ENode(AtomOp.ACC_INIT, (z,)))
        acc = ai; mc = ai
        for i in range(N):
            m = eg.add(ENode(AtomOp.MUL, (ws[i], a_[i])))
            acc = eg.add(ENode(AtomOp.ACC_STEP, (acc, m)))
            mc = eg.add(ENode(AtomOp.MAC, (ws[i], a_[i], mc)))
        eg._union(acc, mc)
        c = eg._canon(acc)

    eg.saturate(FAST_RULES, max_iter=30, max_classes=5000)
    for r in FPGA_RULES: r(eg)
    eg.rebuild()

    cid = eg._canon(c)
    _, stats = eg.extract_fpga_optimal(cid)
    rtl_code, _ = generate_rtl(eg, cid, f"hwine_{op.name.lower()}_{N}", 8)
    return rtl_code, stats


def gen_vivado_tcl(top: str, clk_period_ns: float = 5.0) -> str:
    """Generate Vivado TCL script for synthesis + implementation."""
    return f"""# Auto-generated Vivado TCL for {top}
# Run: vivado -source synth_{top}.tcl

set part xc7z020clg400-1
create_project hwine_{top} ./hwine_{top} -part $part -force
add_files {{{OUT}/{top}.sv}}
set_property top {top} [current_fileset]

# Timing constraints
create_clock -period {clk_period_ns} [get_ports clk]

# Synthesis strategy
synth_design -top {top} -part $part -flatten_hierarchy rebuilt

# Reports
report_utilization -file utilization_{top}.rpt
report_timing_summary -file timing_{top}.rpt

# Implementation
opt_design
place_design
route_design

report_utilization -file utilization_impl_{top}.rpt
report_timing_summary -file timing_impl_{top}.rpt

puts "Synthesis complete for {top}"
"""


