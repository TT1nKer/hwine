def gen_testbench(rtl_code: str, top: str, N: int, op: AtomOp, data_width: int = 8) -> str:
    """Generate self-checking testbench with random vectors."""
    # Check if RTL has clk port
    has_clk = 'clk' in rtl_code.split(');')[0] if ');' in rtl_code else False

    lines = []
    lines.append(f"// Self-checking testbench for {top}")
    lines.append(f"// Generated by hwine — {N} elements, {op.name}")
    lines.append(f"`timescale 1ns / 1ps")
    lines.append(f"")
    lines.append(f"module tb_{top}();")
    if has_clk:
        lines.append(f"  logic clk = 0;")
        lines.append(f"  logic rst_n = 0;")
    lines.append(f"  logic signed [{data_width-1}:0] result;")

    # Declare input variables
    if op == AtomOp.ADD:
        for i in range(N):
            lines.append(f"  logic signed [{data_width-1}:0] v{i};")
    elif op in (AtomOp.REDUCE_MIN, AtomOp.REDUCE_MAX):
        for i in range(N):
            lines.append(f"  logic signed [{data_width-1}:0] v{i};")
    else:  # MAC
        for i in range(N):
            lines.append(f"  logic signed [{data_width-1}:0] w{i};")
            lines.append(f"  logic signed [{data_width-1}:0] a{i};")

    lines.append(f"")
    lines.append(f"  {top} dut(.*);")
    if has_clk:
        lines.append(f"  always #5 clk = ~clk;")
    lines.append(f"")
    lines.append(f"  integer errors = 0;")
    lines.append(f"  integer tests  = 0;")
    lines.append(f"")
    lines.append(f"  initial begin")
    lines.append(f"    $display(\"Testbench: {top} ({op.name}, {N} elements)\");")
    if has_clk:
        lines.append(f"    rst_n = 0;")
        lines.append(f"    #20 rst_n = 1;")
    else:
        lines.append(f"    #5;")
    lines.append(f"")

    # Generate random test vectors
    lines.append(f"    // Test 1: all zeros")
    for i in range(N):
        if op == AtomOp.ADD:
            lines.append(f"    v{i} = 0;")
        elif op in (AtomOp.REDUCE_MIN, AtomOp.REDUCE_MAX):
            lines.append(f"    v{i} = 0;")
        else:
            lines.append(f"    w{i} = 0; a{i} = 0;")
    lines.append(f"    #20;")
    lines.append(f"    tests++;")
    if op == AtomOp.ADD:
        lines.append(f"    if (result !== 0) begin")
    elif op == AtomOp.REDUCE_MIN:
        lines.append(f"    if (result !== 0) begin")
    elif op == AtomOp.REDUCE_MAX:
        lines.append(f"    if (result !== 0) begin")
    else:
        lines.append(f"    if (result !== 0) begin")
    lines.append(f"      $display(\"FAIL zero test: got %d\", result);")
    lines.append(f"      errors++;")
    lines.append(f"    end")
    lines.append(f"")

    # Random tests
    lines.append(f"    // Test 2-10: random vectors")
    lines.append(f"    repeat(10) begin")
    for i in range(N):
        val = abs(hash(f"seed{i}")) % 128
        if op == AtomOp.ADD:
            lines.append(f"      v{i} = {val};")
        elif op in (AtomOp.REDUCE_MIN, AtomOp.REDUCE_MAX):
            lines.append(f"      v{i} = {val};")
        else:
            lines.append(f"      w{i} = {val}; a{i} = {val % 16 + 1};")
    lines.append(f"      #20;")
    lines.append(f"      tests++;")
    lines.append(f"    end")
    lines.append(f"")

    lines.append(f"    #100;")
    lines.append(f"    $display(\"tests=%0d errors=%0d\", tests, errors);")
    lines.append(f"    if (errors == 0) $display(\"PASS\");")
    lines.append(f"    else $display(\"FAIL\");")
    lines.append(f"    $finish;")
    lines.append(f"  end")
    lines.append(f"endmodule")
    return "\n".join(lines)


def run_iverilog(rtl_path: str, tb_path: str, top: str) -> dict:
    """Compile and run with iverilog, return results."""
    vvp_path = os.path.join(OUT, f"{top}.vvp")

    # Compile
    r = subprocess.run(
        ["iverilog", "-g2012", "-o", vvp_path, rtl_path, tb_path],
        capture_output=True, text=True, timeout=30
    )
    if r.returncode != 0:
        return {"pass": False, "error": r.stderr, "stage": "compile"}

    # Run
    r = subprocess.run(
        ["vvp", vvp_path],
        capture_output=True, text=True, timeout=30
    )
    passed = "PASS" in r.stdout and "errors=0" in r.stdout and "FAIL" not in r.stdout
    return {"pass": passed, "output": r.stdout, "stage": "simulate"}


